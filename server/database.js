import { randomBytes, scryptSync, timingSafeEqual, createHash } from 'node:crypto'
import { mkdirSync } from 'node:fs'
import { DatabaseSync } from 'node:sqlite'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SESSION_DURATION_MS = 12 * 60 * 60 * 1000
const SERVER_DIRECTORY = dirname(fileURLToPath(import.meta.url))
const PASSWORD_HASH_PREFIX = 'scrypt'
const PASSWORD_SALT_BYTES = 16
const PASSWORD_HASH_BYTES = 64

export function createPasswordHash(password) {
  if (typeof password !== 'string' || password.length < 14 || password.length > 256) {
    throw new Error('Password must be at least 14 characters and no more than 256 characters.')
  }
  const salt = randomBytes(PASSWORD_SALT_BYTES).toString('hex')
  const hash = scryptSync(password, salt, PASSWORD_HASH_BYTES).toString('hex')
  return `${PASSWORD_HASH_PREFIX}$${salt}$${hash}`
}

function parsePasswordHash(encodedHash) {
  const match = typeof encodedHash === 'string'
    ? /^scrypt\$([a-f0-9]{32})\$([a-f0-9]{128})$/i.exec(encodedHash)
    : null
  if (!match) {
    throw new Error(
      'OWNER_PASSWORD_HASH must be a scrypt hash generated by `npm run owner:hash`; plaintext passwords are not accepted.',
    )
  }
  return { salt: match[1], hash: match[2] }
}

export function readOwnerCredentials(environment = process.env) {
  const username = environment.OWNER_USERNAME?.trim()
  if (!username) throw new Error('OWNER_USERNAME is required; set it to SakshiComputer.')
  if (environment.NODE_ENV === 'production' && username !== 'SakshiComputer') {
    throw new Error('OWNER_USERNAME must be SakshiComputer.')
  }
  if (!/^[a-zA-Z0-9._-]{3,64}$/.test(username)) {
    throw new Error('OWNER_USERNAME must be a valid 3-64 character owner username.')
  }
  const encodedHash = environment.OWNER_PASSWORD_HASH
  if (!encodedHash) {
    throw new Error('OWNER_PASSWORD_HASH is required; generate it locally with `npm run owner:hash`.')
  }
  const passwordHash = parsePasswordHash(encodedHash)
  return { username, encodedHash, ...passwordHash }
}

export async function ensureConfiguredOwner(database, ownerCredentials) {
  return database.transaction(async (transaction) => {
    const existing = await getRow(
      transaction,
      'SELECT id, username FROM owners WHERE username = ? COLLATE NOCASE',
      [ownerCredentials.username],
    )
    if (existing) return { id: existing.id, username: existing.username }

    const owner = {
      id: randomBytes(16).toString('hex'),
      username: ownerCredentials.username,
      passwordSalt: ownerCredentials.salt,
      passwordHash: ownerCredentials.hash,
    }
    await transaction.execute(
      'INSERT INTO owners (id, username, password_salt, password_hash, created_at) VALUES (?, ?, ?, ?, ?)',
      [
        owner.id,
        owner.username,
        owner.passwordSalt,
        owner.passwordHash,
        new Date().toISOString(),
      ],
    )
    return { id: owner.id, username: owner.username }
  })
}

function createLocalDatabase(databasePath) {
  const resolvedPath = resolve(SERVER_DIRECTORY, databasePath || './data/sakshi.sqlite')
  mkdirSync(dirname(resolvedPath), { recursive: true })
  const rawDatabase = new DatabaseSync(resolvedPath)
  rawDatabase.exec('PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL;')

  return {
    async exec(sql) {
      rawDatabase.exec(sql)
    },
    async execute(sql, args = []) {
      const statement = rawDatabase.prepare(sql)
      if (statement.columns().length) {
        return { rows: statement.all(...args), rowsAffected: 0 }
      }
      const result = statement.run(...args)
      return { rows: [], rowsAffected: Number(result.changes) }
    },
    async transaction(callback) {
      rawDatabase.exec('BEGIN IMMEDIATE')
      try {
        const result = await callback(this)
        rawDatabase.exec('COMMIT')
        return result
      } catch (error) {
        try {
          rawDatabase.exec('ROLLBACK')
        } catch (rollbackError) {
          throw new AggregateError([error, rollbackError], 'Database transaction and rollback both failed.')
        }
        throw error
      }
    },
    async close() {
      rawDatabase.close()
    },
  }
}

function databaseConfiguration(databasePath) {
  const url = process.env.TURSO_DATABASE_URL
  const authToken = process.env.TURSO_AUTH_TOKEN
  const engine = process.env.TURSO_DATABASE_ENGINE
  const production = process.env.NODE_ENV === 'production'

  if (Boolean(url) !== Boolean(authToken)) {
    throw new Error('Set both TURSO_DATABASE_URL and TURSO_AUTH_TOKEN to use Turso.')
  }
  if (production && (!url || !authToken)) {
    throw new Error(
      'Production requires TURSO_DATABASE_URL and TURSO_AUTH_TOKEN; refusing to create or use a local database.',
    )
  }
  if (!url) {
    if (engine) throw new Error('TURSO_DATABASE_ENGINE requires Turso URL and token configuration.')
    return { kind: 'local', databasePath }
  }
  if (!['libsql', 'tursodb'].includes(engine)) {
    throw new Error('Set TURSO_DATABASE_ENGINE to "libsql" or "tursodb" to match your Turso database.')
  }
  return { kind: 'remote', url, authToken, engine }
}

async function createRemoteDatabase({ url, authToken, engine }) {
  const client = engine === 'tursodb'
    ? (await import('@tursodatabase/serverless/compat')).createClient({ url, authToken })
    : (await import('@libsql/client')).createClient({ url, authToken })

  return {
    async execute(sql, args = []) {
      return client.execute({ sql, args })
    },
    async transaction(callback) {
      const transaction = await client.transaction('write')
      const adapter = {
        execute: (sql, args = []) => transaction.execute({ sql, args }),
      }
      try {
        const result = await callback(adapter)
        await transaction.commit()
        return result
      } catch (error) {
        try {
          await transaction.rollback()
        } catch (rollbackError) {
          throw new AggregateError([error, rollbackError], 'Database transaction and rollback both failed.')
        }
        throw error
      }
    },
    async close() {
      await client.close()
    },
  }
}

async function initializeSchema(database, local) {
  if (local) {
    await database.exec(`
      CREATE TABLE IF NOT EXISTS owners (
        id TEXT PRIMARY KEY,
        username TEXT NOT NULL COLLATE NOCASE UNIQUE,
        password_salt TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        created_at TEXT NOT NULL
      );
      CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        owner_id TEXT NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
        expires_at INTEGER NOT NULL
      );
      CREATE TABLE IF NOT EXISTS applications (
        id TEXT PRIMARY KEY,
        data TEXT NOT NULL,
        status TEXT NOT NULL CHECK (status IN ('Draft', 'Form ready', 'Submitted', 'Account opened')),
        submitted_on TEXT,
        account_opened_on TEXT,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
      );
      CREATE INDEX IF NOT EXISTS applications_updated_at ON applications(updated_at DESC);
      CREATE INDEX IF NOT EXISTS sessions_expires_at ON sessions(expires_at);
    `)
  } else {
    for (const statement of [
      `CREATE TABLE IF NOT EXISTS owners (
        id TEXT PRIMARY KEY,
        username TEXT NOT NULL COLLATE NOCASE UNIQUE,
        password_salt TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        created_at TEXT NOT NULL
      )`,
      `CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        owner_id TEXT NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
        expires_at INTEGER NOT NULL
      )`,
      `CREATE TABLE IF NOT EXISTS applications (
        id TEXT PRIMARY KEY,
        data TEXT NOT NULL,
        status TEXT NOT NULL CHECK (status IN ('Draft', 'Form ready', 'Submitted', 'Account opened')),
        submitted_on TEXT,
        account_opened_on TEXT,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
      )`,
      'CREATE INDEX IF NOT EXISTS applications_updated_at ON applications(updated_at DESC)',
      'CREATE INDEX IF NOT EXISTS sessions_expires_at ON sessions(expires_at)',
    ]) {
      await database.execute(statement)
    }
  }

  const applicationColumns = await database.execute('PRAGMA table_info(applications)')
  if (!applicationColumns.rows.some((column) => column.name === 'account_opened_on')) {
    await database.execute('ALTER TABLE applications ADD COLUMN account_opened_on TEXT')
  }
  await database.execute('DELETE FROM sessions WHERE expires_at <= ?', [Date.now()])
}

export async function openDatabase(databasePath = process.env.DATABASE_PATH) {
  const configuration = databaseConfiguration(databasePath)
  return openConfiguredDatabase(configuration)
}

export async function openTursoDatabase({ initialize = true } = {}) {
  const configuration = databaseConfiguration(process.env.DATABASE_PATH)
  if (configuration.kind !== 'remote') {
    throw new Error('This command requires Turso URL, auth token, and engine configuration.')
  }
  return openConfiguredDatabase(configuration, initialize)
}

async function openConfiguredDatabase(configuration, initialize = true) {
  const database = configuration.kind === 'local'
    ? createLocalDatabase(configuration.databasePath)
    : await createRemoteDatabase(configuration)
  try {
    if (initialize) await initializeSchema(database, configuration.kind === 'local')
    return database
  } catch (error) {
    await database.close()
    throw error
  }
}

export function resolveDatabasePath(databasePath = process.env.DATABASE_PATH) {
  return resolve(SERVER_DIRECTORY, databasePath || './data/sakshi.sqlite')
}

export function getDatabaseDiagnostics() {
  const url = process.env.TURSO_DATABASE_URL
  let hostname = 'local'
  if (url) {
    try {
      hostname = new URL(url).hostname || 'unknown'
    } catch {
      hostname = 'invalid-url'
    }
  }
  return {
    hostname,
    engine: process.env.TURSO_DATABASE_ENGINE || (url ? 'unknown' : 'local-sqlite'),
  }
}

async function getRow(database, sql, args = []) {
  const result = await database.execute(sql, args)
  return result.rows[0] || null
}

function normalizeOwnerUsername(username) {
  return typeof username === 'string' ? username.trim() : ''
}

function validateNewOwnerUsername(normalizedUsername) {
  if (normalizedUsername.length < 3 || normalizedUsername.length > 64) {
    throw new Error('Username must be between 3 and 64 characters.')
  }
  if (!/^[a-zA-Z0-9._-]+$/.test(normalizedUsername)) {
    throw new Error('Username may only contain letters, numbers, dots, underscores, and hyphens.')
  }
}

function hashPassword(password, salt) {
  return scryptSync(password, salt, 64).toString('hex')
}

function validatePassword(password) {
  if (typeof password !== 'string' || password.length < 14 || password.length > 256) {
    throw new Error('Password must be at least 14 characters and no more than 256 characters.')
  }
}

export async function createOwner(database, username, password) {
  const normalizedUsername = normalizeOwnerUsername(username)
  validateNewOwnerUsername(normalizedUsername)
  validatePassword(password)

  const id = randomBytes(16).toString('hex')
  const salt = randomBytes(16).toString('hex')
  const passwordHash = hashPassword(password, salt)
  await database.transaction(async (transaction) => {
    const owners = await getRow(transaction, 'SELECT COUNT(*) AS count FROM owners')
    if (Number(owners.count) > 0) {
      throw new Error('The one-time owner setup has already been completed for this database.')
    }
    await transaction.execute(
      'INSERT INTO owners (id, username, password_salt, password_hash, created_at) VALUES (?, ?, ?, ?, ?)',
      [id, normalizedUsername, salt, passwordHash, new Date().toISOString()],
    )
  })
  return { id, username: normalizedUsername }
}

export async function authenticateOwner(database, username, password, credentials = readOwnerCredentials()) {
  const normalizedUsername = normalizeOwnerUsername(username)
  if (normalizedUsername.toLocaleLowerCase() !== credentials.username.toLocaleLowerCase()) {
    scryptSync(password, credentials.salt, PASSWORD_HASH_BYTES)
    return {
      owner: null,
      ownerFound: false,
      passwordVerified: false,
      failureStage: 'OWNER_NOT_FOUND',
    }
  }
  const actualHash = scryptSync(password, credentials.salt, PASSWORD_HASH_BYTES)
  const expectedHash = Buffer.from(credentials.hash, 'hex')
  if (!timingSafeEqual(actualHash, expectedHash)) {
    return {
      owner: null,
      ownerFound: true,
      passwordVerified: false,
      failureStage: 'PASSWORD_MISMATCH',
    }
  }
  const owner = await getRow(
    database,
    'SELECT id, username FROM owners WHERE username = ? COLLATE NOCASE',
    [credentials.username],
  )
  if (!owner) {
    return {
      owner: null,
      ownerFound: false,
      passwordVerified: false,
      failureStage: 'OWNER_NOT_FOUND',
    }
  }
  return {
    owner: { id: owner.id, username: owner.username },
    ownerFound: true,
    passwordVerified: true,
    failureStage: null,
  }
}

export async function createSession(database, ownerId) {
  const token = randomBytes(32).toString('base64url')
  const expiresAt = Date.now() + SESSION_DURATION_MS
  await database.execute(
    'INSERT INTO sessions (token_hash, owner_id, expires_at) VALUES (?, ?, ?)',
    [hashSessionToken(token), ownerId, expiresAt],
  )
  return { token, expiresAt }
}

export async function findSession(database, token) {
  if (!token) return null
  const row = await getRow(database, `
    SELECT owners.id, owners.username, sessions.expires_at
    FROM sessions
    JOIN owners ON owners.id = sessions.owner_id
    WHERE sessions.token_hash = ? AND sessions.expires_at > ?
  `, [hashSessionToken(token), Date.now()])
  return row ? { id: row.id, username: row.username, expiresAt: row.expires_at } : null
}

export async function deleteSession(database, token) {
  if (token) {
    await database.execute('DELETE FROM sessions WHERE token_hash = ?', [hashSessionToken(token)])
  }
}

function hashSessionToken(token) {
  return createHash('sha256').update(token).digest('hex')
}

